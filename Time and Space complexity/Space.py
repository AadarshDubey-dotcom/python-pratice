# what is space copmplexity?
"""Space Complexity → The measure of memory required by an algorithm until it executes completely.

It depends on:

Input space → Memory used to store input data.

Auxiliary space → Extra memory used during execution (temporary arrays, recursion stack).

Fixed part → Constants, program instructions, compiler overhead."""

#Common Notations
"""Space complexity is usually expressed in Big‑O notation:

O(1) → Constant space (e.g., accessing an array element).

O(log n) → Logarithmic space (e.g., binary search recursion depth).

O(n) → Linear space (e.g., storing an array of size n).

O(n²) → Quadratic space (e.g., 2D matrix operations)."""